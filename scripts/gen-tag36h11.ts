const out = `${header}

// Generated by scripts/gen-tag36h11.ts from tag36h11.c (SHA-256 ${SOURCE_SHA256.slice(0, 12)}…).
// Do not edit by hand.

/**
 * The 587 codes, 36 bits each, as 9 hex digits, IDs in order (8 per row).
 * Bit i of a code (i = 0 is the most significant of the 36) is the cell at
 * column TAG36H11_BIT_X[i], row TAG36H11_BIT_Y[i] of the 8 × 8 black-square
 * grid; 1 = white.
 */
export const TAG36H11_CODES_HEX: readonly string[] = [
${rows.join('\n')}
];

export const TAG36H11_BIT_X: readonly number[] = [${bitX.join(', ')}];
export const TAG36H11_BIT_Y: readonly number[] = [${bitY.join(', ')}];
`;

const target = fileURLToPath(new URL('../src/tags/tag36h11.ts', import.meta.url));
writeFileSync(target, out);
console.log(`wrote ${target}: ${hex.length} codes`);

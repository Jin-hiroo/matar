/**
 * Generates src/tags/tag36h11.ts from AprilTag 3's tag36h11.c.
 *
 *   curl -fsSLo /tmp/tag36h11.c https://raw.githubusercontent.com/AprilRobotics/apriltag/a29f685ff40564e951f3ea276e518e7d541cdd05/tag36h11.c
 *   pnpm tsx scripts/gen-tag36h11.ts /tmp/tag36h11.c && pnpm prettier --write src/tags/tag36h11.ts
 *
 * Expected SHA-256 of that file:
 * 38ff6e308067eb32ccf624e9cc5e7a75b45ad82b3cf9f80980cb86ebaa88512b
 * The input is parsed as text only; nothing in it is executed.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE_SHA256 = '38ff6e308067eb32ccf624e9cc5e7a75b45ad82b3cf9f80980cb86ebaa88512b';
const SOURCE_URL =
  'https://github.com/AprilRobotics/apriltag/blob/a29f685ff40564e951f3ea276e518e7d541cdd05/tag36h11.c';

const path = process.argv[2];
if (!path) throw new Error('usage: gen-tag36h11.ts <path to tag36h11.c>');
const bytes = readFileSync(path);
const sha = createHash('sha256').update(bytes).digest('hex');
if (sha !== SOURCE_SHA256) throw new Error(`unexpected SHA-256 ${sha}`);
const src = bytes.toString('utf8');

const codes = [...src.matchAll(/0x([0-9a-f]{16})UL/g)].map((m) => m[1]!);
const bitX: number[] = [];
const bitY: number[] = [];
for (const m of src.matchAll(/bit_x\[(\d+)\] = (\d+);/g)) bitX[Number(m[1])] = Number(m[2]);
for (const m of src.matchAll(/bit_y\[(\d+)\] = (\d+);/g)) bitY[Number(m[1])] = Number(m[2]);
if (codes.length !== 587 || bitX.length !== 36 || bitY.length !== 36) {
  throw new Error(`parse failed: ${codes.length} codes, ${bitX.length}/${bitY.length} bits`);
}
for (const c of codes)
  if (!c.startsWith('0000000')) throw new Error(`code wider than 36 bits: ${c}`);

const hex = codes.map((c) => c.slice(7)); // 9 hex digits = 36 bits
const rows: string[] = [];
for (let i = 0; i < hex.length; i += 8) rows.push(`  '${hex.slice(i, i + 8).join(' ')}', // ${i}`);

